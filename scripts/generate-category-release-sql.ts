/**
 * Writes the production release files for the category tree (never runs them):
 *   release-output/prod-migration-20261116010000.sql (+ .rollback.sql)
 *   release-output/prod-categories-seed.sql (+ .rollback.sql)
 *   release-output/subcategories-release.sha256
 *
 * Usage: npx tsx scripts/generate-category-release-sql.ts
 *
 * The seed comes from lib/category-seed.ts. Seeded rows get deterministic ids ("cseed" + md5 of the slug), so the
 * seed is idempotent and its rollback only ever deletes rows the seed itself created.
 */
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { CATEGORY_SEED } from "../lib/category-seed";

const MIGRATION = "20261116010000_category_tree";
const PREREQUISITE = "20261114030000_content_pages";
const root = resolve(process.cwd());
const out = resolve(root, "release-output");

const sha256 = (text: string) => createHash("sha256").update(text, "utf8").digest("hex");
const lf = (text: string) => text.replace(/\r\n/g, "\n");
/** Dollar-quoted literal; the tag never occurs in the seed data. */
const q = (value: string) => {
  if (value.includes("$bg$")) throw new Error(`unsafe literal: ${value}`);
  return `$bg$${value}$bg$`;
};
/** Same expression in SQL and here: 'cseed' || left(md5('bagati-category:' || slug), 20). */
export const seedId = (slug: string) => `cseed${createHash("md5").update(`bagati-category:${slug}`).digest("hex").slice(0, 20)}`;

const migrationBody = lf(readFileSync(resolve(root, `prisma/migrations/${MIGRATION}/migration.sql`), "utf8"));
const checksum = sha256(migrationBody);

const existing = CATEGORY_SEED.filter((top) => top.existing);
const newTops = CATEGORY_SEED.filter((top) => !top.existing);
const children = CATEGORY_SEED.flatMap((top) => top.children.map((child) => ({ ...child, parentSlug: top.slug })));
const seededSlugs = [...newTops.map((top) => top.slug), ...children.map((child) => child.slug)];
const inList = (values: string[]) => values.map(q).join(", ");

const migrationSql = `-- BAGATI production migration ${MIGRATION}
-- Generated by scripts/generate-category-release-sql.ts from the committed prisma/migrations file (LF).
-- Prisma checksum (sha256 of the LF file): ${checksum}
-- Requires PostgreSQL 13+ (gen_random_uuid). Runs in ONE transaction; any error rolls everything back.
-- Take and verify a backup BEFORE running this file. Run it BEFORE deploying the new application code.
-- Additive only: three nullable/defaulted columns on "Category" (sortOrder, iconKey, imageUrl), one index, three CHECKs,
-- two triggers. No existing row, name, slug or product changes. Category rows are untouched except that sortOrder = 0.
-- Independent of 20261115120000_seller_voen_verification (either may be applied first).

BEGIN;

-- 1. Guard: abort unless the database is exactly in the expected state.
DO $$
BEGIN
  IF to_regclass(format('%I.%I', current_schema(), '_prisma_migrations')) IS NULL THEN
    RAISE EXCEPTION 'ABORT: table _prisma_migrations not found in schema %', current_schema();
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM "_prisma_migrations"
    WHERE migration_name = '${PREREQUISITE}' AND finished_at IS NOT NULL AND rolled_back_at IS NULL
  ) THEN
    RAISE EXCEPTION 'ABORT: prerequisite migration ${PREREQUISITE} is not finished';
  END IF;
  IF EXISTS (SELECT 1 FROM "_prisma_migrations" WHERE migration_name = '${MIGRATION}') THEN
    RAISE EXCEPTION 'ABORT: ${MIGRATION} is already recorded in _prisma_migrations';
  END IF;
  IF to_regclass(format('%I.%I', current_schema(), 'Category')) IS NULL OR to_regclass(format('%I.%I', current_schema(), 'Product')) IS NULL THEN
    RAISE EXCEPTION 'ABORT: table Category or Product does not exist';
  END IF;
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = current_schema() AND table_name = 'Category' AND column_name IN ('sortOrder', 'iconKey', 'imageUrl')
  ) THEN
    RAISE EXCEPTION 'ABORT: a Category column of this migration already exists';
  END IF;
  IF to_regprocedure(format('%I.%I()', current_schema(), 'category_tree_guard')) IS NOT NULL
     OR to_regprocedure(format('%I.%I()', current_schema(), 'category_delete_guard')) IS NOT NULL THEN
    RAISE EXCEPTION 'ABORT: a trigger function of this migration already exists';
  END IF;
  -- The depth trigger would not re-check existing rows: refuse if the data is already deeper than two levels.
  IF EXISTS (SELECT 1 FROM "Category" c JOIN "Category" p ON p."id" = c."parentId" WHERE p."parentId" IS NOT NULL) THEN
    RAISE EXCEPTION 'ABORT: existing categories are nested deeper than two levels; fix them first';
  END IF;
  IF EXISTS (SELECT 1 FROM "Category" WHERE "parentId" = "id") THEN
    RAISE EXCEPTION 'ABORT: a category is its own parent';
  END IF;
END
$$;

-- 2. Body: the migration file, unchanged.
-- >>> BEGIN prisma/migrations/${MIGRATION}/migration.sql
${migrationBody.trimEnd()}
-- <<< END prisma/migrations/${MIGRATION}/migration.sql

-- 3. Record the migration exactly as "prisma migrate deploy" would.
INSERT INTO "_prisma_migrations"
  ("id", "checksum", "finished_at", "migration_name", "logs", "rolled_back_at", "started_at", "applied_steps_count")
VALUES
  (gen_random_uuid()::text, '${checksum}', now(), '${MIGRATION}', NULL, NULL, now(), 1);

-- 4. Verification (results are shown before COMMIT).
SELECT migration_name, checksum, finished_at IS NOT NULL AS finished, rolled_back_at, applied_steps_count
FROM "_prisma_migrations" WHERE migration_name = '${MIGRATION}';

SELECT column_name, data_type, is_nullable, column_default
FROM information_schema.columns
WHERE table_schema = current_schema() AND table_name = 'Category' AND column_name IN ('sortOrder', 'iconKey', 'imageUrl')
ORDER BY column_name;

SELECT c.conname FROM pg_constraint c
WHERE c.conrelid = to_regclass(format('%I.%I', current_schema(), 'Category')) AND c.contype = 'c' ORDER BY c.conname;

SELECT tgname FROM pg_trigger WHERE tgrelid = to_regclass(format('%I.%I', current_schema(), 'Category')) AND NOT tgisinternal ORDER BY tgname;

SELECT indexname FROM pg_indexes WHERE schemaname = current_schema() AND tablename = 'Category' ORDER BY indexname;

SELECT count(*) AS categories, count(*) FILTER (WHERE "parentId" IS NULL) AS top_levels, (SELECT count(*) FROM "Product") AS products FROM "Category";

COMMIT;
`;

const migrationRollbackSql = `-- BAGATI rollback of ${MIGRATION}. Runs in ONE transaction.
-- Order: deploy the previous application build FIRST, run prod-categories-seed.rollback.sql (if the seed was run),
-- then this file. It drops only what the migration added (columns sortOrder/iconKey/imageUrl, index, CHECKs,
-- triggers and their functions). Category rows, parentId and all products stay.
-- Refuses while any category still has an icon or an uploaded photo (seed not rolled back / admin data would be lost).

BEGIN;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM "_prisma_migrations" WHERE migration_name = '${MIGRATION}') THEN
    RAISE EXCEPTION 'ABORT: ${MIGRATION} is not recorded in _prisma_migrations';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = current_schema() AND table_name = 'Category' AND column_name = 'iconKey'
  ) THEN
    RAISE EXCEPTION 'ABORT: Category.iconKey not found; nothing to roll back';
  END IF;
  IF EXISTS (SELECT 1 FROM "Category" WHERE "iconKey" IS NOT NULL OR "imageUrl" IS NOT NULL) THEN
    RAISE EXCEPTION 'ABORT: categories still have icons or photos. Run prod-categories-seed.rollback.sql first; export admin photos with: SELECT slug, "imageUrl" FROM "Category" WHERE "imageUrl" IS NOT NULL';
  END IF;
END
$$;

DROP TRIGGER "Category_delete_guard" ON "Category";
DROP TRIGGER "Category_tree_guard" ON "Category";
DROP FUNCTION "category_delete_guard"();
DROP FUNCTION "category_tree_guard"();
ALTER TABLE "Category" DROP CONSTRAINT "Category_imageUrl_length_check";
ALTER TABLE "Category" DROP CONSTRAINT "Category_iconKey_format_check";
ALTER TABLE "Category" DROP CONSTRAINT "Category_parent_not_self_check";
DROP INDEX "Category_parentId_sortOrder_idx";
ALTER TABLE "Category" DROP COLUMN "sortOrder", DROP COLUMN "iconKey", DROP COLUMN "imageUrl";
DELETE FROM "_prisma_migrations" WHERE migration_name = '${MIGRATION}';

-- Verification.
SELECT column_name FROM information_schema.columns
WHERE table_schema = current_schema() AND table_name = 'Category' ORDER BY ordinal_position;
SELECT tgname FROM pg_trigger WHERE tgrelid = to_regclass(format('%I.%I', current_schema(), 'Category')) AND NOT tgisinternal;
SELECT count(*) AS recorded FROM "_prisma_migrations" WHERE migration_name = '${MIGRATION}';

COMMIT;
`;

const existingValues = existing.map((top) => `    (${q(top.slug)}, ${q(top.iconKey)}, ${top.sortOrder})`).join(",\n");
const topValues = newTops.map((top) => `    (${q(seedId(top.slug))}, ${q(top.name)}, ${q(top.slug)}, ${top.sortOrder}, ${q(top.iconKey)})`).join(",\n");
const childValues = children.map((child) => `    (${q(seedId(child.slug))}, ${q(child.name)}, ${q(child.slug)}, ${q(child.parentSlug)}, ${child.sortOrder})`).join(",\n");

const seedSql = `-- BAGATI production seed: two-level category tree (lib/category-seed.ts, reviewed list).
-- Generated by scripts/generate-category-release-sql.ts. Runs in ONE transaction; any error rolls everything back.
-- Run AFTER prod-migration-20261116010000.sql (guarded) and preferably right after deploying the new build.
-- Idempotent: running it again changes nothing (verified in the rehearsal).
--   * ${existing.length} existing top-levels: only iconKey and sortOrder are set, and only while iconKey is still NULL
--     (never seeded and never edited in admin). Name, slug and photo stay as they are.
--   * ${newTops.length} new top-levels and ${children.length} subcategories: INSERT ... ON CONFLICT ("slug") DO NOTHING, with
--     deterministic ids ('cseed' || left(md5('bagati-category:' || slug), 20)).
--   * Product rows are never touched (checked before COMMIT against a snapshot).

BEGIN;

-- 1. Guards.
DO $$
DECLARE
  missing TEXT;
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM "_prisma_migrations"
    WHERE migration_name = '${MIGRATION}' AND finished_at IS NOT NULL AND rolled_back_at IS NULL
  ) THEN
    RAISE EXCEPTION 'ABORT: migration ${MIGRATION} is not applied';
  END IF;
  IF to_regprocedure(format('%I.%I()', current_schema(), 'category_tree_guard')) IS NULL THEN
    RAISE EXCEPTION 'ABORT: trigger function category_tree_guard is missing';
  END IF;
  SELECT string_agg(expected.slug, ', ') INTO missing
  FROM (VALUES ${existing.map((top) => `(${q(top.slug)})`).join(", ")}) AS expected(slug)
  WHERE NOT EXISTS (SELECT 1 FROM "Category" c WHERE c."slug" = expected.slug AND c."parentId" IS NULL);
  IF missing IS NOT NULL THEN
    RAISE EXCEPTION 'ABORT: expected existing top-level categories are missing: %', missing;
  END IF;
  -- A new top-level slug that already exists as a subcategory would leave its subcategories without a parent.
  SELECT string_agg(c."slug", ', ') INTO missing FROM "Category" c
  WHERE c."slug" IN (${inList(newTops.map((top) => top.slug))}) AND c."parentId" IS NOT NULL;
  IF missing IS NOT NULL THEN
    RAISE EXCEPTION 'ABORT: these new top-level slugs already exist as subcategories: %', missing;
  END IF;
END
$$;

CREATE TEMP TABLE "seed_product_snapshot" ON COMMIT DROP AS
  SELECT "id", "categoryId", "updatedAt", "name", "slug", "status" FROM "Product";
CREATE TEMP TABLE "seed_existing_snapshot" ON COMMIT DROP AS
  SELECT "id", "name", "slug", "parentId", "isActive", "imageUrl" FROM "Category";

-- 2. Existing top-levels: icon and order only (first run only; admin edits are never overwritten).
UPDATE "Category" AS c
SET "iconKey" = v.icon_key, "sortOrder" = v.sort_order
FROM (VALUES
${existingValues}
) AS v(slug, icon_key, sort_order)
WHERE c."slug" = v.slug AND c."parentId" IS NULL AND c."iconKey" IS NULL;

-- 3. New top-levels (no photo; Avtomobil and Ev heyvanları use the shipped photos by slug in the app).
INSERT INTO "Category" ("id", "name", "slug", "parentId", "isActive", "sortOrder", "iconKey")
SELECT v.id, v.name, v.slug, NULL, TRUE, v.sort_order, v.icon_key
FROM (VALUES
${topValues}
) AS v(id, name, slug, sort_order, icon_key)
ON CONFLICT ("slug") DO NOTHING;

-- 4. Subcategories under their top-level (matched by slug; the depth trigger checks every row).
INSERT INTO "Category" ("id", "name", "slug", "parentId", "isActive", "sortOrder", "iconKey")
SELECT v.id, v.name, v.slug, p."id", TRUE, v.sort_order, NULL
FROM (VALUES
${childValues}
) AS v(id, name, slug, parent_slug, sort_order)
JOIN "Category" p ON p."slug" = v.parent_slug AND p."parentId" IS NULL
ON CONFLICT ("slug") DO NOTHING;

-- 5. Safety checks before COMMIT: products unchanged, existing names/slugs/photos/parents unchanged.
DO $$
DECLARE
  changed INTEGER;
BEGIN
  SELECT count(*) INTO changed FROM (
    (SELECT "id", "categoryId", "updatedAt", "name", "slug", "status" FROM "Product"
     EXCEPT SELECT * FROM "seed_product_snapshot")
    UNION ALL
    (SELECT * FROM "seed_product_snapshot"
     EXCEPT SELECT "id", "categoryId", "updatedAt", "name", "slug", "status" FROM "Product")
  ) AS diff;
  IF changed > 0 THEN
    RAISE EXCEPTION 'ABORT: % product rows differ from the snapshot', changed;
  END IF;
  SELECT count(*) INTO changed FROM "seed_existing_snapshot" s
  JOIN "Category" c ON c."id" = s."id"
  WHERE (c."name", c."slug", c."parentId", c."isActive", c."imageUrl") IS DISTINCT FROM (s."name", s."slug", s."parentId", s."isActive", s."imageUrl");
  IF changed > 0 THEN
    RAISE EXCEPTION 'ABORT: % existing categories changed name/slug/parent/active/photo', changed;
  END IF;
END
$$;

-- 6. Verification (shown before COMMIT).
SELECT count(*) FILTER (WHERE "parentId" IS NULL) AS top_levels,
       count(*) FILTER (WHERE "parentId" IS NOT NULL) AS subcategories,
       count(*) FILTER (WHERE "id" LIKE 'cseed%') AS seeded_rows,
       (SELECT count(*) FROM "Product") AS products
FROM "Category";

SELECT p."sortOrder", p."name" AS top_level, p."slug", p."iconKey", count(c."id") AS subcategories
FROM "Category" p LEFT JOIN "Category" c ON c."parentId" = p."id"
WHERE p."parentId" IS NULL
GROUP BY p."id" ORDER BY p."sortOrder", p."name";

-- Seed slugs that were skipped because the slug already existed (normally none; review if listed).
SELECT c."slug", c."id", c."parentId" FROM "Category" c
WHERE c."slug" IN (${inList(seededSlugs)}) AND c."id" NOT LIKE 'cseed%';

COMMIT;
`;

const existingResets = existing.map((top) => `    (${q(top.slug)}, ${q(top.iconKey)}, ${top.sortOrder})`).join(",\n");
const seedRollbackSql = `-- BAGATI rollback of prod-categories-seed.sql. Runs in ONE transaction.
-- Deletes only rows the seed created (ids 'cseed...'), subcategories first, and resets iconKey/sortOrder of the
-- existing top-levels only where they still hold the seeded values (admin edits are kept).
-- Refuses while any seeded category has products or a subcategory the seed did not create: move those products
-- back first (admin "Məhsulları köçür" or a reviewed UPDATE), then run this file. Never changes Product rows.

BEGIN;

DO $$
DECLARE
  blocked TEXT;
BEGIN
  IF to_regprocedure(format('%I.%I()', current_schema(), 'category_tree_guard')) IS NULL THEN
    RAISE EXCEPTION 'ABORT: migration ${MIGRATION} is not applied';
  END IF;
  SELECT string_agg(c."slug" || ' (' || n || ' products)', ', ') INTO blocked
  FROM "Category" c JOIN (SELECT "categoryId", count(*) AS n FROM "Product" GROUP BY "categoryId") p ON p."categoryId" = c."id"
  WHERE c."id" LIKE 'cseed%';
  IF blocked IS NOT NULL THEN
    RAISE EXCEPTION 'ABORT: seeded categories still have products: %', blocked;
  END IF;
  SELECT string_agg(c."slug", ', ') INTO blocked
  FROM "Category" c JOIN "Category" p ON p."id" = c."parentId"
  WHERE p."id" LIKE 'cseed%' AND c."id" NOT LIKE 'cseed%';
  IF blocked IS NOT NULL THEN
    RAISE EXCEPTION 'ABORT: admin-created subcategories under seeded top-levels: %', blocked;
  END IF;
END
$$;

CREATE TEMP TABLE "seed_product_snapshot" ON COMMIT DROP AS SELECT "id", "categoryId", "updatedAt" FROM "Product";

DELETE FROM "Category" WHERE "id" LIKE 'cseed%' AND "parentId" IS NOT NULL;
DELETE FROM "Category" WHERE "id" LIKE 'cseed%';

UPDATE "Category" AS c
SET "iconKey" = NULL, "sortOrder" = 0
FROM (VALUES
${existingResets}
) AS v(slug, icon_key, sort_order)
WHERE c."slug" = v.slug AND c."parentId" IS NULL AND c."iconKey" = v.icon_key AND c."sortOrder" = v.sort_order;

DO $$
BEGIN
  IF EXISTS (
    (SELECT "id", "categoryId", "updatedAt" FROM "Product" EXCEPT SELECT * FROM "seed_product_snapshot")
    UNION ALL
    (SELECT * FROM "seed_product_snapshot" EXCEPT SELECT "id", "categoryId", "updatedAt" FROM "Product")
  ) THEN
    RAISE EXCEPTION 'ABORT: product rows changed';
  END IF;
END
$$;

-- Verification.
SELECT count(*) AS categories, count(*) FILTER (WHERE "id" LIKE 'cseed%') AS seeded_rows_left,
       count(*) FILTER (WHERE "iconKey" IS NOT NULL) AS with_icon FROM "Category";

COMMIT;
`;

mkdirSync(out, { recursive: true });
const files: [string, string][] = [
  [`prod-migration-20261116010000.sql`, migrationSql],
  [`prod-migration-20261116010000.rollback.sql`, migrationRollbackSql],
  [`prod-categories-seed.sql`, seedSql],
  [`prod-categories-seed.rollback.sql`, seedRollbackSql],
];
const lines: string[] = [];
for (const [name, text] of files) {
  writeFileSync(resolve(out, name), text, { encoding: "utf8" });
  lines.push(`${sha256(text)}  ${name}`);
}
lines.push(`${checksum}  prisma/migrations/${MIGRATION}/migration.sql (Prisma checksum, LF)`);
writeFileSync(resolve(out, "subcategories-release.sha256"), `${lines.join("\n")}\n`, "utf8");
console.log(lines.join("\n"));
console.log(`seed: ${existing.length} existing top-levels, ${newTops.length} new top-levels, ${children.length} subcategories`);
