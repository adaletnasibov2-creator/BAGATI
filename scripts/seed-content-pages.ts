/**
 * Idempotent seed of the four content pages from today's texts (lib/content-pages.ts CONTENT_PAGE_DEFAULTS).
 * Creates a page (and one initial revision) only when its slug has no row; existing pages are never changed.
 *
 *   npx tsx scripts/seed-content-pages.ts          # seed through Prisma (DATABASE_URL)
 *   npx tsx scripts/seed-content-pages.ts --sql    # print the same seed as SQL (release-output/prod-content-pages-seed.sql)
 */
import { CONTENT_PAGE_DEFAULTS, CONTENT_PAGE_SLUGS } from "../lib/content-pages";

export const SEED_NOTE = "İlkin mətn (köhnə səhifədən)";

/** Dollar-quoted literal with a tag that cannot occur in the text. */
function dollar(text: string): string {
  let tag = "c";
  while (text.includes(`$${tag}$`)) tag += "c";
  return `$${tag}$${text}$${tag}$`;
}

export function seedSql(): string {
  const parts = [
    "-- BAGATI content pages seed (idempotent). Generated by scripts/seed-content-pages.ts --sql from lib/content-pages.ts.",
    "-- Inserts a page and one initial revision only when the slug has no row; existing pages are never changed.",
    "-- Run AFTER prod-migration-20261114030000.sql. Safe to run more than once.",
    "BEGIN;",
    "DO $$ BEGIN",
    "  IF to_regclass(format('%I.%I', current_schema(), 'ContentPage')) IS NULL THEN RAISE EXCEPTION 'ABORT: table ContentPage not found (run the migration first)'; END IF;",
    "END $$;",
  ];
  for (const slug of CONTENT_PAGE_SLUGS) {
    const { title, body } = CONTENT_PAGE_DEFAULTS[slug];
    parts.push(
      `WITH page AS (`,
      `  INSERT INTO "ContentPage" ("id", "slug", "title", "body", "published", "updatedAt")`,
      `  VALUES (gen_random_uuid()::text, '${slug}', ${dollar(title)}, ${dollar(body)}, true, now())`,
      `  ON CONFLICT ("slug") DO NOTHING RETURNING "id", "title", "body"`,
      `) INSERT INTO "ContentPageRevision" ("id", "pageId", "title", "body", "note", "createdAt")`,
      `SELECT gen_random_uuid()::text, "id", "title", "body", ${dollar(SEED_NOTE)}, now() FROM page;`,
    );
  }
  parts.push(
    `SELECT "slug", "title", char_length("body") AS body_chars, "published", (SELECT count(*) FROM "ContentPageRevision" r WHERE r."pageId" = p."id") AS revisions FROM "ContentPage" p ORDER BY "slug";`,
    "COMMIT;",
    "",
  );
  return parts.join("\n");
}

export async function seedWithPrisma(): Promise<string[]> {
  const { prisma } = await import("../lib/prisma");
  const created: string[] = [];
  for (const slug of CONTENT_PAGE_SLUGS) {
    const { title, body } = CONTENT_PAGE_DEFAULTS[slug];
    const done = await prisma.$transaction(async (tx) => {
      if (await tx.contentPage.findUnique({ where: { slug }, select: { id: true } })) return false;
      const page = await tx.contentPage.create({ data: { slug, title, body, published: true } });
      await tx.contentPageRevision.create({ data: { pageId: page.id, title, body, note: SEED_NOTE } });
      return true;
    }).catch((error: unknown) => {
      // A concurrent seed created it first: fine (idempotent).
      if (error && typeof error === "object" && "code" in error && (error as { code: string }).code === "P2002") return false;
      throw error;
    });
    if (done) created.push(slug);
  }
  await prisma.$disconnect();
  return created;
}

if (require.main === module) {
  if (process.argv.includes("--sql")) process.stdout.write(seedSql());
  else seedWithPrisma().then((created) => console.log(created.length ? `Created: ${created.join(", ")}` : "Nothing to do: all pages exist."));
}
